#!/usr/bin/env python3
"""Refresh _data/youtube.yml with the latest items from the Skillberry YouTube channel.

Collects videos and shorts from the channel's public RSS feed and playlists from the
channel's /playlists tab, then keeps the N most recently published items overall.
Standard library only, no API key. If YouTube can't be reached, the existing file is
left untouched so a transient failure never empties the page.

Usage:  python3 scripts/update_youtube.py [--limit 5]
"""

import argparse
import datetime as dt
import json
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA_FILE = ROOT / "_data" / "youtube.yml"
CHANNEL_HANDLE = "skillberry-ai"
CHANNEL_ID = "UC2XX4fT9cDZuZWgCOaw9lEw"

NS = {
    "a": "http://www.w3.org/2005/Atom",
    "yt": "http://www.youtube.com/xml/schemas/2015",
    "media": "http://search.yahoo.com/mrss/",
}
UA = {"User-Agent": "Mozilla/5.0 (skillberry-ai.github.io updater)", "Accept-Language": "en"}


def fetch(url: str) -> str:
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read().decode("utf-8")


def parse_feed(xml_text: str) -> ET.Element:
    return ET.fromstring(xml_text)


def uploads() -> list[dict]:
    """Videos and shorts, from the channel feed (the 15 most recent uploads)."""
    root = parse_feed(fetch(f"https://www.youtube.com/feeds/videos.xml?channel_id={CHANNEL_ID}"))
    items = []
    for e in root.findall("a:entry", NS):
        vid = e.findtext("yt:videoId", namespaces=NS)
        link = e.find("a:link", NS).get("href", "")
        kind = "short" if "/shorts/" in link else "video"
        items.append({
            "type": kind,
            "id": vid,
            "title": e.findtext("a:title", namespaces=NS),
            "url": f"https://www.youtube.com/shorts/{vid}" if kind == "short"
                   else f"https://www.youtube.com/watch?v={vid}",
            "thumbnail": f"https://i.ytimg.com/vi/{vid}/hqdefault.jpg",
            "published": e.findtext("a:published", namespaces=NS),
        })
    return items


def _walk(node):
    if isinstance(node, dict):
        yield node
        for v in node.values():
            yield from _walk(v)
    elif isinstance(node, list):
        for v in node:
            yield from _walk(v)


def playlist_ids() -> list[str]:
    """Playlist IDs listed on the channel's /playlists tab (best effort: page markup changes)."""
    html = fetch(f"https://www.youtube.com/@{CHANNEL_HANDLE}/playlists")
    m = re.search(r"var ytInitialData\s*=\s*(\{.*?\});</script>", html, re.S)
    if not m:
        return []
    ids = []
    for d in _walk(json.loads(m.group(1))):
        pid = None
        if "gridPlaylistRenderer" in d:
            pid = d["gridPlaylistRenderer"].get("playlistId")
        elif d.get("contentType") == "LOCKUP_CONTENT_TYPE_PLAYLIST":
            pid = d.get("contentId")
        if pid and pid not in ids:
            ids.append(pid)
    return ids


def playlist(pid: str) -> dict | None:
    root = parse_feed(fetch(f"https://www.youtube.com/feeds/videos.xml?playlist_id={pid}"))
    entries = root.findall("a:entry", NS)
    first = entries[0].findtext("yt:videoId", namespaces=NS) if entries else None
    return {
        "type": "playlist",
        "id": pid,
        "title": root.findtext("a:title", namespaces=NS),
        "url": f"https://www.youtube.com/playlist?list={pid}",
        "thumbnail": f"https://i.ytimg.com/vi/{first}/hqdefault.jpg" if first else None,
        "published": root.findtext("a:published", namespaces=NS),
        "count": len(entries),
    }


def yaml_str(s) -> str:
    return json.dumps("" if s is None else str(s), ensure_ascii=False)  # JSON strings are valid YAML


def write(items: list[dict]) -> None:
    lines = [
        "# Generated by scripts/update_youtube.py (run daily by .github/workflows/youtube.yml).",
        "# Manual edits will be overwritten.",
        f"channel_id: {CHANNEL_ID}",
        f"updated: {dt.date.today().isoformat()}",
        "items:" if items else "items: []",
    ]
    for it in items:
        lines.append(f"  - type: {it['type']}")
        for key in ("id", "title", "url", "thumbnail", "published"):
            if it.get(key):
                lines.append(f"    {key}: {yaml_str(it[key])}")
        if "count" in it:
            lines.append(f"    count: {it['count']}")
    DATA_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=5)
    args = ap.parse_args()

    try:
        items = uploads()
    except Exception as exc:  # network, parse
        print(f"could not read channel feed, keeping existing data: {exc}", file=sys.stderr)
        return 0
    try:
        for pid in playlist_ids():
            if pl := playlist(pid):
                items.append(pl)
    except Exception as exc:
        print(f"skipping playlists: {exc}", file=sys.stderr)

    items.sort(key=lambda i: i.get("published") or "", reverse=True)
    write(items[: args.limit])
    print(f"wrote {min(len(items), args.limit)} item(s) to {DATA_FILE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
